import { useEffect, useState } from 'react';
import { Button } from '../components/Button';
import { Card } from '../components/Card';
import { Modal } from '../components/Modal';
import { fetchExample, type ExampleResponse } from '../lib/api';

type ApiState = { status: 'loading' } | { status: 'success'; data: ExampleResponse } | { status: 'error'; message: string };

export function DashboardPage(): React.JSX.Element {
  const [apiState, setApiState] = useState<ApiState>({ status: 'loading' });
  const [modalOpen, setModalOpen] = useState(false);

  function loadExample(): void {
    setApiState({ status: 'loading' });
    fetchExample()
      .then((data) => setApiState({ status: 'success', data }))
      .catch((error: unknown) =>
        setApiState({ status: 'error', message: error instanceof Error ? error.message : 'Unknown error' }),
      );
  }

  useEffect(() => {
    loadExample();
  }, []);

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-2xl font-semibold text-text">Dashboard</h1>
        <p className="mt-1 text-sm text-muted">
          This is a placeholder starter page generated by create-my-app. Replace it with your real application.
        </p>
      </div>

      <div className="grid gap-6 sm:grid-cols-2">
        <Card title="Welcome">
          <p className="text-sm text-muted">
            This card, the layout around it, and the colors all come from the scaffolding templates — see the
            generated README for where to edit each piece.
          </p>
          <Button variant="secondary" className="mt-4" onClick={() => setModalOpen(true)}>
            View details
          </Button>
        </Card>

        <Card title="API status">
          {apiState.status === 'loading' ? (
            <p className="text-sm text-muted" role="status">
              Loading...
            </p>
          ) : null}
          {apiState.status === 'success' ? (
            <div className="flex flex-col gap-2">
              <p className="text-sm text-text">{apiState.data.message}</p>
              <p className="text-xs text-muted">Received at {new Date(apiState.data.receivedAt).toLocaleString()}</p>
            </div>
          ) : null}
          {apiState.status === 'error' ? (
            <div className="flex flex-col gap-3">
              <p className="text-sm text-danger" role="alert">
                Couldn&apos;t reach the API: {apiState.message}
              </p>
              <Button variant="secondary" onClick={loadExample} className="self-start">
                Retry
              </Button>
            </div>
          ) : null}
        </Card>

        <Card title="Recent activity" className="sm:col-span-2">
          <p className="text-sm text-muted">No recent activity yet.</p>
        </Card>
      </div>

      <Modal open={modalOpen} onClose={() => setModalOpen(false)} title="Example modal">
        <p className="text-sm text-muted">
          This is the shared Modal component. It's not used elsewhere in the starter yet, but it's wired up and
          ready — see src/components/Modal.tsx.
        </p>
        <Button className="mt-4" onClick={() => setModalOpen(false)}>
          Close
        </Button>
      </Modal>
    </div>
  );
}
