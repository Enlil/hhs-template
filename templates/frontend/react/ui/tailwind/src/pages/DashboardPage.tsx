import { useState } from 'react';
import { Button } from '../components/Button';
import { Card } from '../components/Card';
import { Modal } from '../components/Modal';
import { Snackbar } from '../components/Snackbar';
import { useExample } from '../lib/useExample';

export function DashboardPage(): React.JSX.Element {
  const { state: apiState, reload: loadExample } = useExample();
  const [modalOpen, setModalOpen] = useState(false);

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1>Dashboard</h1>
        <p className="mt-1 text-muted">
          This is a placeholder starter page generated by create-my-app. Replace it with your real application.
        </p>
      </div>

      <div className="grid gap-6 sm:grid-cols-2">
        <Card title="Welcome">
          <p className="text-muted">
            This card, the layout around it, and the colors all come from the scaffolding templates — see the
            generated README for where to edit each piece.
          </p>
          <Button variant="secondary" className="mt-4" onClick={() => setModalOpen(true)}>
            View details
          </Button>
        </Card>

        <Card title="API status">
          {apiState.status === 'loading' ? (
            <p className="text-muted" role="status">
              Loading...
            </p>
          ) : null}
          {apiState.status === 'success' ? (
            <div className="flex flex-col gap-1">
              <p>{apiState.data.message}</p>
              <p className="text-content-3 text-muted">Received at {new Date(apiState.data.receivedAt).toLocaleString()}</p>
            </div>
          ) : null}
          {apiState.status === 'error' ? (
            <div className="flex flex-col gap-4">
              <Snackbar status="alert">Couldn&apos;t reach the API: {apiState.message}</Snackbar>
              <Button variant="tertiary" onClick={loadExample} className="self-start">
                Retry
              </Button>
            </div>
          ) : null}
        </Card>

        <Card title="Recent activity" className="sm:col-span-2">
          <p className="text-muted">No recent activity yet.</p>
        </Card>
      </div>

      <Modal open={modalOpen} onClose={() => setModalOpen(false)} title="Example modal">
        <p className="text-muted">
          This is the shared Modal component. It's not used elsewhere in the starter yet, but it's wired up and
          ready — see src/components/Modal.tsx.
        </p>
        <Button className="mt-4" onClick={() => setModalOpen(false)}>
          Close
        </Button>
      </Modal>
    </div>
  );
}
