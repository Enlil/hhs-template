import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import Card from '@mui/material/Card';
import CardActions from '@mui/material/CardActions';
import CardContent from '@mui/material/CardContent';
import Dialog from '@mui/material/Dialog';
import DialogActions from '@mui/material/DialogActions';
import DialogContent from '@mui/material/DialogContent';
import DialogContentText from '@mui/material/DialogContentText';
import DialogTitle from '@mui/material/DialogTitle';
import Typography from '@mui/material/Typography';
import { useState } from 'react';
import { Snackbar } from '../components/Snackbar';
import { useExample } from '../lib/useExample';

export function DashboardPage(): React.JSX.Element {
  const { state: apiState, reload: loadExample } = useExample();
  const [modalOpen, setModalOpen] = useState(false);

  return (
    <Box sx={{ display: 'flex', flexDirection: 'column', gap: 3 }}>
      <Box>
        <Typography variant="h1" component="h1">
          Dashboard
        </Typography>
        <Typography color="text.secondary" sx={{ mt: 0.5 }}>
          This is a placeholder starter page generated by create-my-app. Replace it with your real application.
        </Typography>
      </Box>

      <Box sx={{ display: 'grid', gap: 3, gridTemplateColumns: { xs: 'minmax(0, 1fr)', sm: 'repeat(2, minmax(0, 1fr))' } }}>
        <Card>
          <CardContent sx={{ p: 3, pb: 1 }}>
            <Typography variant="h2" component="h2" gutterBottom>
              Welcome
            </Typography>
            <Typography color="text.secondary">
              This card, the layout around it, and the colors all come from the scaffolding templates — see the
              generated README for where to edit each piece.
            </Typography>
          </CardContent>
          <CardActions sx={{ px: 3, pb: 3 }}>
            <Button variant="contained" color="secondary" onClick={() => setModalOpen(true)}>
              View details
            </Button>
          </CardActions>
        </Card>

        <Card>
          <CardContent sx={{ p: 3, pb: apiState.status === 'error' ? 1 : 3 }}>
            <Typography variant="h2" component="h2" gutterBottom>
              API status
            </Typography>
            {apiState.status === 'loading' ? (
              <Typography color="text.secondary" role="status">
                Loading...
              </Typography>
            ) : null}
            {apiState.status === 'success' ? (
              <>
                <Typography>{apiState.data.message}</Typography>
                <Typography variant="body2" color="text.secondary">
                  Received at {new Date(apiState.data.receivedAt).toLocaleString()}
                </Typography>
              </>
            ) : null}
            {apiState.status === 'error' ? (
              <Snackbar status="alert">Couldn&apos;t reach the API: {apiState.message}</Snackbar>
            ) : null}
          </CardContent>
          {apiState.status === 'error' ? (
            <CardActions sx={{ px: 3, pb: 3 }}>
              <Button variant="outlined" onClick={loadExample}>
                Retry
              </Button>
            </CardActions>
          ) : null}
        </Card>

        <Card sx={{ gridColumn: { sm: 'span 2' } }}>
          <CardContent sx={{ p: 3, '&:last-child': { pb: 3 } }}>
            <Typography variant="h2" component="h2" gutterBottom>
              Recent activity
            </Typography>
            <Typography color="text.secondary">No recent activity yet.</Typography>
          </CardContent>
        </Card>
      </Box>

      <Dialog open={modalOpen} onClose={() => setModalOpen(false)} aria-labelledby="example-dialog-title">
        <DialogTitle id="example-dialog-title">Example modal</DialogTitle>
        <DialogContent>
          <DialogContentText>
            This is a Material UI dialog. It's not used elsewhere in the starter yet, but it's wired up and ready —
            see src/pages/DashboardPage.tsx.
          </DialogContentText>
        </DialogContent>
        <DialogActions sx={{ px: 3, pb: 3 }}>
          <Button variant="contained" onClick={() => setModalOpen(false)}>
            Close
          </Button>
        </DialogActions>
      </Dialog>
    </Box>
  );
}
